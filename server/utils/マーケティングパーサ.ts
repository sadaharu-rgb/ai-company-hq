/**
 * マーケティングパーサ — 公開済み.md / アイデア.md を構造化データに変換する純関数群
 *
 * 設計原則：
 * - .md を正本のまま読み取り専用ビューとして提供
 * - 純関数なのでテストしやすい
 * - 失敗時は空配列を返す（呼び出し側でハンドリング不要）
 */

export type 公開済み投稿 = {
  通し番号: string         // "#001" "#002" など
  日付: string             // "2026-05-11"
  タイトル: string
  内容: string
  ハッシュタグ: string[]
  ツイートID?: string
  反応?: string
  連動note?: string
}

export type ネタ候補 = {
  ID: string              // "Q-01" "D-08" "N1" など
  タイトル: string
  カテゴリ: string         // "セキュリティ" "デプロイ" "Claude活用" 等（セクション名から推定）
  評価: 'S' | 'A' | 'B' | '不明'
  草稿あり: boolean
  生成日?: string          // ⭐2026-05-15生成 などの注記から
}

// ─── 公開済み.md パーサ ──────────────────────────────────────

/**
 * 公開済み.md の本文から X投稿エントリを抽出する
 * 「### #001:」「### #002:」のような見出しを区切りとして利用
 */
export function 公開済み投稿を抽出する(本文: string): 公開済み投稿[] {
  const 結果: 公開済み投稿[] = []
  // X投稿セクションを抽出（「## 🐦 X投稿（時系列）」から「## 」または末尾まで）
  const X投稿セクション正規表現 = /## 🐦 X投稿[\s\S]*?(?=\n## |$)/
  const セクションマッチ = X投稿セクション正規表現.exec(本文)
  if (!セクションマッチ) return 結果

  const セクション = セクションマッチ[0]
  // 各投稿ブロックを抽出
  const ブロック分割 = セクション.split(/\n### /).slice(1) // 最初の "## 🐦 X投稿..." は除外

  for (const ブロック of ブロック分割) {
    const 投稿 = ブロックを公開済み投稿にパース('### ' + ブロック)
    if (投稿) 結果.push(投稿)
  }
  return 結果
}

function ブロックを公開済み投稿にパース(ブロック: string): 公開済み投稿 | null {
  // ヘッダー行：「### #001: 2026-05-11 Rei統合発表 ⭐ 1本目」
  const ヘッダー行マッチ = /^### (#\d+):\s*(\d{4}-\d{2}-\d{2})\s+(.+?)(?:\s+⭐.*)?$/m.exec(ブロック)
  if (!ヘッダー行マッチ) return null

  const [, 通し番号, 日付, タイトル] = ヘッダー行マッチ

  const 内容マッチ = /\*\*内容\*\*：(.+?)(?:\n|$)/.exec(ブロック)
  const ハッシュタグマッチ = /\*\*ハッシュタグ\*\*：`(.+?)`/.exec(ブロック)
  const ツイートIDマッチ = /\*\*ツイートID\*\*：[`「]?(\d+)/.exec(ブロック)
  const 反応マッチ = /\*\*反応\*\*：(.+?)(?:\n|$)/.exec(ブロック)
  const 連動noteマッチ = /\*\*連動note\*\*：`?(.+?)`?(?:\n|$)/.exec(ブロック)

  const ハッシュタグ = ハッシュタグマッチ
    ? ハッシュタグマッチ[1].split(/\s+/).filter(t => t.startsWith('#'))
    : []

  return {
    通し番号: 通し番号.trim(),
    日付: 日付.trim(),
    タイトル: タイトル.trim(),
    内容: 内容マッチ?.[1].trim() ?? '',
    ハッシュタグ,
    ツイートID: ツイートIDマッチ?.[1],
    反応: 反応マッチ?.[1].trim(),
    連動note: 連動noteマッチ?.[1].trim(),
  }
}

// ─── アイデア.md パーサ ──────────────────────────────────────

/**
 * アイデア.md の本文からネタ候補を抽出する
 * 「### Q-01: タイトル」「#### N1: ...」など 3〜4 つの # 見出しを区切りとして利用
 *
 * パース戦略：
 * - ## トップレベルセクション ＝ カテゴリ
 * - その中の ### または #### で始まる「ID: タイトル」型ヘッダーをネタとして抽出
 * - 同セクション内の ### 評価サブグループ（例：### 🥇 S級）は ID パターンでない限り無視
 */
export function ネタ候補を抽出する(本文: string): ネタ候補[] {
  const 結果: ネタ候補[] = []
  const セクション分割 = 本文.split(/\n## /).slice(1)

  for (const セクション of セクション分割) {
    const セクション本文 = '## ' + セクション
    const カテゴリ = セクションからカテゴリ推定(セクション本文)

    // 全行を走査して ### or #### の ID形式ヘッダーをネタとして拾う
    const 行群 = セクション本文.split('\n')
    let 現在ブロック: string[] = []
    let 現在ヘッダー: string | null = null

    const ブロック確定 = () => {
      if (現在ヘッダー !== null) {
        const ブロック本文 = [現在ヘッダー, ...現在ブロック].join('\n')
        const ネタ = ブロックをネタ候補にパース(ブロック本文, カテゴリ)
        if (ネタ) 結果.push(ネタ)
      }
      現在ブロック = []
      現在ヘッダー = null
    }

    for (const 行 of 行群) {
      const ヘッダーマッチ = /^(#{3,4})\s+([A-Z]+-?\d+|N\d+):\s*(.+)$/.exec(行)
      if (ヘッダーマッチ) {
        ブロック確定()
        現在ヘッダー = 行
      } else if (現在ヘッダー !== null) {
        現在ブロック.push(行)
      }
    }
    ブロック確定()
  }
  return 結果
}

function セクションからカテゴリ推定(セクション: string): string {
  const 見出しマッチ = /^## .*?([🛡️🏗️🤖🚂📊🎨💰🔧📝🆕📌🗑️📈🔄🏆📚📖]+\s*[ぁ-ゔァ-ヴー一-龥a-zA-Z・]+(?:系|管理|案|チェック|防止|キュー|戦略|発信|棚卸|候補|測定|ネタ集|履歴|別管理|削除|案件|構造|集計|表|防御|タイミング|順|総合))/m.exec(セクション)
  if (見出しマッチ) return 見出しマッチ[1].trim()

  // フォールバック：絵文字+短い名前で
  const シンプル見出しマッチ = /^## (.+?)(?:\n|$)/m.exec(セクション)
  return シンプル見出しマッチ?.[1].trim() ?? '未分類'
}

function ブロックをネタ候補にパース(ブロック: string, カテゴリ: string): ネタ候補 | null {
  // ヘッダー：「### Q-01: axios脆弱性、自分の本番アプリにもあった 【草稿あり】」
  // または「#### N1: AI会議 15部門プロンプト + CEO統合判定 ⭐⭐⭐」
  // または「### S-01: サイレント失敗の罠 ⭐2026-05-15生成」
  const ヘッダー行マッチ = /^#{3,4}\s+([A-Z]+-?\d+|N\d+):\s*(.+?)$/m.exec(ブロック)
  if (!ヘッダー行マッチ) return null

  const [, ID, タイトル生] = ヘッダー行マッチ
  // タイトルから「【草稿あり】」「⭐⭐⭐」「⭐2026-05-15生成」を分離
  const 草稿あり = /【草稿あり】/.test(タイトル生)
  const 評価マッチ = /⭐⭐⭐|⭐⭐|⭐(?!\d)/.exec(タイトル生)
  const 生成日マッチ = /⭐(\d{4}-\d{2}-\d{2})生成/.exec(タイトル生)

  let 評価: ネタ候補['評価'] = '不明'
  if (評価マッチ?.[0] === '⭐⭐⭐') 評価 = 'S'
  else if (評価マッチ?.[0] === '⭐⭐') 評価 = 'A'
  else if (評価マッチ?.[0] === '⭐') 評価 = 'B'

  // クリーンなタイトル
  const タイトル = タイトル生
    .replace(/【草稿あり】/g, '')
    .replace(/⭐⭐⭐|⭐⭐|⭐\d{4}-\d{2}-\d{2}生成|⭐(?!\d)/g, '')
    .replace(/\s+/g, ' ')
    .trim()

  return {
    ID: ID.trim(),
    タイトル,
    カテゴリ,
    評価,
    草稿あり,
    生成日: 生成日マッチ?.[1],
  }
}

// ─── サマリ集計 ──────────────────────────────────────

export type ネタサマリ = {
  総数: number
  S級: number
  A級: number
  B級: number
  不明: number
  草稿あり: number
  カテゴリ別: Record<string, number>
}

export function ネタサマリを集計する(ネタ一覧: ネタ候補[]): ネタサマリ {
  const サマリ: ネタサマリ = {
    総数: ネタ一覧.length,
    S級: 0,
    A級: 0,
    B級: 0,
    不明: 0,
    草稿あり: 0,
    カテゴリ別: {},
  }
  for (const ネタ of ネタ一覧) {
    if (ネタ.評価 === 'S') サマリ.S級++
    else if (ネタ.評価 === 'A') サマリ.A級++
    else if (ネタ.評価 === 'B') サマリ.B級++
    else サマリ.不明++

    if (ネタ.草稿あり) サマリ.草稿あり++

    サマリ.カテゴリ別[ネタ.カテゴリ] = (サマリ.カテゴリ別[ネタ.カテゴリ] ?? 0) + 1
  }
  return サマリ
}
